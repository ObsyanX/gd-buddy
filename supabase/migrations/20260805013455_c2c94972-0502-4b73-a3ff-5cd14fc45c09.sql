## Preparation beats talent in group discussions

Group discussions look like a test of personality. They are actually a test of preparation: how much relevant material you can recall under pressure, how quickly you can structure it, and how reliably you can deliver it in 30 to 60 second bursts. This guide gives you a complete preparation system — content, structure, delivery, and rehearsal — for campus placement and B-school selection rounds.

## What panels actually score

Most evaluation sheets, whatever the wording, reduce to five dimensions:

- **Content quality** — facts, examples, and reasoning rather than opinion.
- **Structure** — whether your points have a visible skeleton.
- **Communication** — clarity, pace, vocabulary, and audibility.
- **Group behaviour** — listening, crediting, inviting quieter members, handling disagreement.
- **Leadership** — initiating, steering, and summarising.

Notice that only one of the five is about knowing things. Candidates over-invest in content and under-invest in the other four.

## Building your content base

**Four weeks out.** Pick eight to ten themes that generate most placement topics: economy and jobs, technology and AI, education policy, climate and energy, healthcare, gender and social policy, geopolitics, and business or startup strategy.

**Every day.** Read one long-form article per theme rotation and write a five-line note: the claim, one statistic, one counter-argument, one example, one implication. Five lines is deliberate — GD contributions are short, so your notes should be too.

**Every week.** Convert twelve notes into twelve 40-second spoken contributions. Speak them aloud and time them.

By week four you will have roughly fifty deliverable contributions, which covers the overwhelming majority of topics you will encounter, because most topics are recombinations of the same themes.

## Frameworks that rescue you on unfamiliar topics

Memorise three or four and you will never be silent:

- **SPELT** — Social, Political, Economic, Legal, Technological.
- **Stakeholder map** — consumers, businesses, government, workers, environment.
- **Short vs long term** — immediate cost, structural benefit.
- **Cost–benefit–alternative** — what it costs, what it gains, what else could be done instead.

A framework converts panic into a checklist. Even with zero domain knowledge you can contribute: "Let us separate the short-term implementation cost from the long-term structural effect, because the group is arguing across those two timeframes."

## Structuring a single contribution

The best contributions follow one of three micro-structures, each 30 to 45 seconds:

- **Claim → evidence → implication.** The default. State the point, support it, say why it matters.
- **Acknowledge → refine → extend.** For building on someone else. The single most collaborative move available.
- **Counter → concede → reframe.** For disagreement. Push back, grant what is true in their point, then move the frame.

Never make more than two points in one turn. Additional points in the same breath are almost never remembered.

## Group behaviour: the invisible score

Panels watch how you treat people. Concrete behaviours that raise your score:

- Use names. "Building on Rahul's point about credit access…"
- Invite silent members once. "Sneha, you work with this data — what is your view?"
- Disagree with the idea, never the person. "I read that data differently" rather than "You are wrong."
- Yield gracefully when interrupted, then reclaim: "Let me finish that thought in one line."

Behaviours that sink you: interrupting repeatedly, raising your voice, aggressive body language, and monopolising more than roughly a fifth of the airtime in a group of eight.

## Delivery mechanics

- **Pace:** aim for 130 to 150 words per minute. Most nervous candidates exceed 180.
- **Fillers:** "um," "like," "basically," and "actually" cluster at the start of sentences. Replace them with a half-second pause.
- **Volume:** target the far end of the table, not the person next to you.
- **Posture:** upright, forward, hands above the table, feet flat.

Record yourself weekly. Filler counts and pace are the two metrics that improve fastest with feedback and slowest without it.

## A four-week rehearsal schedule

- **Week 1:** Content base. Two AI-moderated practice sessions. Focus purely on speaking without fillers.
- **Week 2:** Frameworks. Three sessions on abstract and unfamiliar topics.
- **Week 3:** Group behaviour. Three sessions where you must credit two people and invite one silent member every time.
- **Week 4:** Full simulation. Four timed sessions with realistic interruption, plus opening and concluding practice on alternate runs.

Review a scored report after every session. Track four numbers over time: words per minute, fillers per minute, share of airtime, and number of contributions that included evidence.

## The day before and the day of

The day before: skim your notes, do not add new material, sleep properly. The day of: read two headline summaries, arrive early, and warm up your voice by speaking aloud for two minutes before you enter the room.

In the room: sit where you can see everyone, carry a pen and paper, and write two words per speaker. Those notes are what make your summary possible.

## The one habit that matters most

Speak out loud, under time pressure, several times a week, and review the recording. Passive reading feels productive and changes almost nothing. Rehearsal changes everything.
