## The mistakes that cost placements

Most candidates lose group discussions in predictable ways. The errors below appear in nearly every placement round, and each one has a specific, learnable fix. Work through them in order — the first four account for the majority of rejections.

## 1. Speaking without structure

**What it looks like:** a stream of loosely connected opinions that runs 90 seconds and leaves no memorable point.

**Why it fails:** evaluators score what they can reconstruct afterwards. Unstructured speech is unscorable.

**Fix:** limit yourself to two points per turn and use claim → evidence → implication. If you cannot state your point in one sentence before you begin, do not begin.

## 2. Confusing volume with contribution

**What it looks like:** speaking the most, interrupting to hold the floor, repeating points in new words.

**Why it fails:** panels track quality per contribution, not total airtime. Dominance also triggers a group-behaviour penalty that is often decisive.

**Fix:** in a group of eight, aim for four to six substantive contributions. Track your airtime in practice sessions; anything beyond a fifth of the total is a warning sign.

## 3. Fabricating facts

**What it looks like:** invented statistics, misattributed reports, confidently wrong dates.

**Why it fails:** one caught error contaminates every other claim you make, and technically literate panels catch them regularly.

**Fix:** signal uncertainty honestly — "roughly," "in the region of," "as of last year." Hedged accuracy scores higher than precise fiction. Build a small bank of numbers you are genuinely sure about.

## 4. Not listening

**What it looks like:** rehearsing your next point while others speak, repeating something already said, missing that the topic has shifted.

**Why it fails:** it is instantly visible, and it makes collaboration impossible.

**Fix:** write two words per speaker on paper. The act of noting forces attention and gives you material for crediting and summarising later.

## 5. Personal attacks disguised as disagreement

**What it looks like:** "You clearly don't understand how markets work."

**Why it fails:** aggression is the fastest route to elimination in a round that explicitly measures group behaviour.

**Fix:** attack the claim, credit the person. "That is a fair concern about pricing, though the demand data points the other way."

## 6. Going silent after a bad start

**What it looks like:** one weak contribution, then withdrawal for the rest of the discussion.

**Why it fails:** recoverable mistakes become fatal when you stop participating. Panels expect resilience.

**Fix:** re-enter within two minutes using a low-risk move: build on someone else's point or ask a clarifying question. Momentum is restored by re-entry, not by waiting for the perfect moment.

## 7. Ignoring the quieter participants

**What it looks like:** four people run the discussion while three never speak.

**Why it fails:** the ability to include others is a leadership marker that senior evaluators weight heavily.

**Fix:** invite one silent participant once, by name, with a specific question. Once is enough — repeated prompting looks performative.

## 8. Poor time awareness

**What it looks like:** introducing a major new argument in the last minute, or being cut off mid-summary.

**Why it fails:** it signals an inability to manage a bounded process.

**Fix:** mentally split the discussion into thirds: exploration, contest, consolidation. Introduce new arguments only in the first two-thirds.

## 9. Filler words and rushed delivery

**What it looks like:** "um," "basically," "like," delivered at 190 words per minute.

**Why it fails:** it reads as anxiety and reduces comprehension, so even good content lands weakly.

**Fix:** replace fillers with a half-second pause — silence sounds deliberate. Target 130 to 150 words per minute. This improves fastest with recorded feedback.

## 10. Preparing content but not delivery

**What it looks like:** three weeks of reading, zero rehearsal, and a first spoken attempt that happens in the actual round.

**Why it fails:** GD is a performance skill. Knowledge that cannot be delivered under interruption is not usable.

**Fix:** at least half your preparation time should be spoken practice under time pressure, with review afterwards.

## A quick self-audit

After each practice session, answer honestly:

- Did every contribution have a structure I could name?
- Did I credit at least one person by name?
- Did I introduce evidence at least twice?
- Was my airtime proportionate?
- Did I re-enter after being interrupted?
- Did I attempt an opening or a summary?

Three or more "no" answers means you are still practising content when you should be practising behaviour.

## How to fix these efficiently

Do not try to fix all ten at once. Pick one per session and make it your only objective. Fixing "two points per turn" for three sessions produces more improvement than vaguely trying to be better across all dimensions. Recorded sessions with per-metric scoring make the difference visible, which is what sustains the habit.
