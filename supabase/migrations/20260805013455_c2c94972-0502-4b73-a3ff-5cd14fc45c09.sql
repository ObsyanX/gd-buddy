## Your body is talking before you are

In a group discussion, evaluators observe you for the entire duration but hear you for only two or three minutes. The rest of the time, their impression is formed by posture, eye contact, gesture, and facial reaction. Non-verbal behaviour is therefore not a garnish on your performance — for most of the round it *is* your performance.

This guide covers what to do with your body before you speak, while you speak, and while others speak.

## Seating and setup

- **Choose sightlines.** Sit where you can see the maximum number of participants without turning your torso. Corners of the table are usually better than the middle of a long side.
- **Keep the surface clear.** A pen, a sheet of paper, and nothing else. Phones, bottles, and folders create fidget opportunities.
- **Plant your feet.** Both feet flat on the floor stops the leg-bounce that is the single most common visible anxiety tell.

## Posture: the default position

Sit upright with a small forward lean of about ten degrees. A forward lean reads as engagement; sitting back reads as detachment; hunching forward over the table reads as tension.

Keep your forearms lightly on the table with hands visible and relaxed. Hidden hands — in your lap, under the table, in pockets — reduce perceived openness. Shoulders down and back, not raised toward the ears.

Hold this as a resting state you can return to after every gesture.

## Eye contact that includes everyone

The most common eye-contact error is addressing only the panel. You are speaking to the group; the panel is observing the group.

- While speaking, sweep across three or four participants, holding each for two to three seconds.
- Include the person who disagrees with you. Avoiding them signals that you are uncomfortable with challenge.
- While listening, look at the speaker roughly 60 to 70 percent of the time. Continuous staring is as unsettling as never looking.

If direct eye contact is difficult, look at the bridge of the nose. It is indistinguishable from the outside.

## Gestures: purposeful, bounded, above the table

Good gestures are illustrative and finite:

- **Enumerating** — fingers for "three reasons."
- **Contrasting** — two hands separating for "on one hand… on the other."
- **Sizing** — hands apart for scale or growth.

Keep gestures within the width of your shoulders and above the table line. Return to the resting position between gestures, so movement remains punctuation rather than background noise.

Avoid entirely: pointing at people, chopping the table, pen clicking, hair touching, face touching, and crossed arms.

## Facial expression and listening behaviour

You are being evaluated most while you are silent. Active-listening signals cost nothing and score well:

- A slow single nod when a point lands.
- Slight brow movement when a claim is surprising.
- Note-taking when a fact is cited — this reads as respect for evidence.

Neutral faces are read as disengaged; visible eye-rolls, smirks, or head-shaking at a speaker are read as hostile and are heavily penalised. Practise a warm neutral: relaxed jaw, soft eyes, mouth at rest with a faint upward set.

## Voice as non-verbal signal

Tone carries more than words in a noisy room:

- **Pace** of 130 to 150 words per minute reads as controlled.
- **Downward inflection** at the end of statements signals conviction; upward inflection turns every sentence into a question.
- **Volume** aimed at the far end of the table, not the nearest person.
- **Pauses** of half a second before a key point create emphasis and eliminate fillers.

Breathe from the diaphragm. Shallow chest breathing thins the voice and is the physical root of most "nervous-sounding" delivery.

## Entering and yielding the floor

Non-verbal entry is more effective than verbal interruption:

- Lift your hand slightly off the table, palm up, and lean forward.
- Catch the speaker's eye and hold it briefly.
- Take a visible in-breath as they finish a clause.

When interrupted, do not escalate volume. Hold your posture, raise one hand slightly, and say "one line to finish." Composure under interruption is one of the most reliable leadership signals available.

## Managing visible nervousness

Physical tells appear in a fixed order: hands, feet, breathing, voice. Intervene early:

- Press your fingertips lightly on the table to stop trembling hands.
- Exhale for four counts before your first contribution.
- Anchor your feet and stop the bounce before it starts.
- Sip water only between contributions, never mid-thought.

Mild nervousness is normal and largely invisible; the visible part is what you can control mechanically.

## Practising non-verbal skills

Video is essential — you cannot self-assess posture from the inside.

- Record a session and watch it **on mute**. Judge only what you see. If you look disengaged with the sound off, you looked disengaged in the room.
- Watch a second time at double speed to expose repetitive fidgets.
- Pick one behaviour per session — for example, hands above the table — and make it the only goal.

## Online and hybrid discussions

Increasingly, GDs are remote. The rules shift:

- Camera at eye level; look at the lens when speaking, at the grid when listening.
- Frame from mid-chest up so gestures are visible.
- Light your face from the front, not behind.
- Nod slightly more than you would in person — the medium flattens signal.

Non-verbal skill is mechanical, learnable, and quick to improve. Two recorded sessions per week for a month will change how you are perceived far more than another month of reading.
